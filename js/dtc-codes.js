const P0_GROUPS = {
  0: 'Fuel/air metering & auxiliary emission controls', 1: 'Fuel and air metering', 2: 'Fuel and air metering (injector circuit)',
  3: 'Ignition system or misfire', 4: 'Auxiliary emission controls', 5: 'Vehicle speed, idle control & auxiliary inputs',
  6: 'Computer output circuits', 7: 'Transmission', 8: 'Transmission', 9: 'Transmission',
};

export function describeDtc(code) {
  if (CODES[code]) return { text: CODES[code], generic: true };
  const sys = { P: 'Powertrain', C: 'Chassis', B: 'Body', U: 'Network' }[code[0]];
  if (code[1] === '1' || code[1] === '3') {
    return { text: `${sys} — manufacturer-specific code (look up for MINI / BMW)`, generic: false };
  }
  if (code[0] === 'P') {
    return { text: `${P0_GROUPS[parseInt(code[2], 16)] ?? 'Powertrain'} — generic code`, generic: false };
  }
  return { text: `${sys} code`, generic: false };
}
